-- Shared vocabulary catalogue (safe to re-run on an existing project).
create table if not exists public.vocabulary (
  id bigint generated by default as identity primary key,
  word text not null,
  v2 text not null default '—',
  v3 text not null default '—',
  meaning text not null,
  part_of_speech text not null default 'Verb',
  example text not null default '',
  example_id text not null default '',
  level text not null default 'Basic',
  created_at timestamptz not null default now()
);
create unique index if not exists vocabulary_word_unique on public.vocabulary (lower(word));
-- VocabRise multi-user schema. Run after the existing vocabulary table/schema.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.user_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  word_id bigint not null references public.vocabulary(id) on delete cascade,
  learned_at timestamptz not null default now(),
  unique (user_id, word_id)
);

create table if not exists public.user_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  daily_target integer not null default 15 check (daily_target between 1 and 100),
  theme text not null default 'light' check (theme in ('light','dark')),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_type text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists user_progress_user_idx on public.user_progress(user_id);
create index if not exists activity_logs_created_idx on public.activity_logs(created_at desc);
create index if not exists activity_logs_user_idx on public.activity_logs(user_id, created_at desc);

create or replace function public.is_vocabrise_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'); $$;

create or replace function public.handle_new_vocabrise_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare uname text;
begin
  uname := lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)));
  insert into public.profiles(id, username) values (new.id, uname)
  on conflict (id) do nothing;
  insert into public.user_settings(user_id) values (new.id) on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_vocabrise on auth.users;
create trigger on_auth_user_created_vocabrise after insert on auth.users
for each row execute procedure public.handle_new_vocabrise_user();

alter table public.profiles enable row level security;
alter table public.user_progress enable row level security;
alter table public.user_settings enable row level security;
alter table public.activity_logs enable row level security;

drop policy if exists "Profiles visible to owner or admin" on public.profiles;
create policy "Profiles visible to owner or admin" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_vocabrise_admin());
-- Deliberately no client insert/update/delete policy on profiles: role is admin-managed only.

drop policy if exists "Users manage own progress; admin reads all" on public.user_progress;
drop policy if exists "Users manage own progress" on public.user_progress;
drop policy if exists "Admin reads all progress" on public.user_progress;
create policy "Users manage own progress" on public.user_progress for all to authenticated
using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Admin reads all progress" on public.user_progress for select to authenticated
using (public.is_vocabrise_admin());

drop policy if exists "Users manage own settings; admin reads all" on public.user_settings;
drop policy if exists "Users manage own settings" on public.user_settings;
drop policy if exists "Admin reads all settings" on public.user_settings;
create policy "Users manage own settings" on public.user_settings for all to authenticated
using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Admin reads all settings" on public.user_settings for select to authenticated
using (public.is_vocabrise_admin());

drop policy if exists "Users add own activity and admin reads all" on public.activity_logs;
create policy "Users add own activity and admin reads all" on public.activity_logs for insert to authenticated
with check (user_id = auth.uid());
drop policy if exists "Users see own activity; admin sees all" on public.activity_logs;
create policy "Users see own activity; admin sees all" on public.activity_logs for select to authenticated
using (user_id = auth.uid() or public.is_vocabrise_admin());

-- Shared vocabulary remains readable to anonymous and authenticated users.
alter table public.vocabulary enable row level security;
drop policy if exists "Vocabulary is readable by everyone" on public.vocabulary;
create policy "Vocabulary is readable by everyone" on public.vocabulary for select to anon, authenticated using (true);

